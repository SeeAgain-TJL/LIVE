test("legacy unclassified archive and existing IndexedDB media survive migration and reload", async ({ page }) => {
  await page.goto("/");
  await expect(page.locator(".galaxy-list article")).toHaveCount(5);
  const seed = createSeed(); const planet = { ...seed.planets[0], name: "迁移前用户星球", galaxyId: null, isDemo: false };
  const now = "2026-01-01T00:00:00.000Z";
  const raw = JSON.stringify({ ...seed, revision: 7, galaxies: seed.galaxies.filter(g => g.id !== "unclassified"), planets: [planet],
    memories: [{ id: "old-memory", planetId: planet.id, kind: "mixed", title: "迁移前照片", body: "这是迁移前的正文。", occurredOn: "2020-02-29", mediaIds: ["old-photo"], createdAt: now, updatedAt: now }],
    media: [{ id: "old-photo", memoryId: "old-memory", kind: "image", name: "original.png", mimeType: "image/png", size: (await readFile("tests/fixtures/memory.png")).length, createdAt: now }],
  }, null, 2);
  const bytes = (await readFile("tests/fixtures/memory.png")).toString("base64");
  await page.evaluate(async ({ raw, bytes }) => {
    await new Promise<void>((resolve, reject) => {
      const request = indexedDB.open("universe-of-me-media", 1);
      request.onupgradeneeded = () => request.result.createObjectStore("blobs");
      request.onerror = () => reject(request.error);
      request.onsuccess = () => {
        const db = request.result; const tx = db.transaction("blobs", "readwrite");
        tx.objectStore("blobs").put(new Blob([Uint8Array.from(atob(bytes), c => c.charCodeAt(0))], { type: "image/png" }), "old-photo");
        tx.oncomplete = () => { db.close(); resolve(); }; tx.onerror = () => reject(tx.error);
      };
    });
    localStorage.setItem("universe-of-me:data:v1", raw);
  }, { raw, bytes });
  await page.reload();
  await page.getByRole("link", { name: "直接打开星系：未分类星系", exact: true }).click();
  await expect(page.locator(".planet-list-item")).toHaveCount(1);
  await page.locator(".planet-list-item").click();
  await page.getByRole("link", { name: "直接打开档案 ↗", exact: true }).click();
  await page.getByRole("button", { name: "列表管理", exact: true }).click();
  await page.getByRole("button", { name: "打开记忆：迁移前照片", exact: true }).click();
  await expect(page.locator(".memory-detail-body")).toHaveText("这是迁移前的正文。");
  await expect.poll(() => page.locator(".memory-detail-panel img").evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(640);
  expect(await page.evaluate(() => localStorage.getItem("universe-of-me:before-galaxies:v1"))).toBe(raw);
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem("universe-of-me:data:v1")!));
  expect(stored.revision).toBe(7); expect(stored.planets[0]).toEqual({ ...planet, galaxyId: "unclassified" });
  await page.reload();
  await openGuide(page);
  await page.getByRole("button", { name: "帮我寻找", exact: true }).click();
  await page.locator(".global-guide-search").getByRole("button", { name: "照片记忆", exact: true }).click();
  await expect.poll(() => page.locator(".memory-detail-panel img").evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(640);
  await page.getByRole("button", { name: "关闭记忆详情", exact: true }).click();
  await page.locator(".planet-info-menu summary").click();
  await page.getByRole("button", { name: "编辑星球资料", exact: true }).click();
  await page.getByLabel("星球名称", { exact: false }).fill("迁移后重新命名");
  await page.getByRole("combobox", { name: "所属星系", exact: true }).selectOption("friendship");
  await page.getByRole("button", { name: "保存星球", exact: true }).click();
  await expect(page.locator(".memory-palace-title h1")).toHaveText("迁移后重新命名");
  await page.getByRole("link", { name: "返回所属星系", exact: true }).click();
  await expect(page).toHaveURL(/\/galaxy\/friendship\?planet=/);
  await page.reload();
  await expect(page.locator(".selection-card h2")).toHaveText("迁移后重新命名");
  await page.getByRole("link", { name: "直接打开档案 ↗", exact: true }).click();
  await openGuide(page);
  await page.getByRole("button", { name: "帮我寻找", exact: true }).click();
  await page.locator(".global-guide-search").getByRole("button", { name: "照片记忆", exact: true }).click();
  await expect(page.locator(".memory-detail-body")).toHaveText("这是迁移前的正文。");
  await expect.poll(() => page.locator(".memory-detail-panel img").evaluate((img: HTMLImageElement) => img.naturalWidth)).toBe(640);
});

