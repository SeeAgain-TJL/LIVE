import { mkdir, writeFile, copyFile } from "node:fs/promises";
import path from "node:path";
import { chromium } from "playwright";

const folder = path.join(process.env.LOCALAPPDATA, "UNIVERSE-OF-ME", "asset-audit", "candidate-assets", "source-forest-evidence");
await mkdir(folder, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1,
  recordVideo: { dir: folder, size: { width: 1440, height: 900 } } });
const page = await context.newPage();
const issues = [];
page.on("pageerror", error => issues.push(error.message));
page.on("console", message => { if (message.type() === "error") issues.push(message.text()); });
page.on("requestfailed", request => { if (!request.failure()?.errorText?.includes("ERR_ABORTED")) issues.push(`${request.url()}: ${request.failure()?.errorText}`); });
const started = Date.now();
await page.goto((process.env.FOREST_LAB_URL || "http://127.0.0.1:3310") + "/forest-source-lab", { waitUntil: "domcontentloaded" });
await page.locator("canvas[data-forest-ready='true']").waitFor({ timeout: 180000 });
const loadedMs = Date.now() - started;
await page.waitForTimeout(4000);
const initial = JSON.parse(await page.locator("canvas").getAttribute("data-forest-metrics") || "{}");
await page.locator(".forest-lab-bar").evaluate(element => { element.style.display = "none"; });
await page.screenshot({ path: path.join(folder, "source-camera.png") });
await page.locator("canvas").click({ position: { x: 720, y: 450 } });
await page.keyboard.down("w");
await page.waitForTimeout(2500);
await page.keyboard.up("w");
await page.screenshot({ path: path.join(folder, "walk-forward.png") });
await page.mouse.move(720, 450);
await page.mouse.down();
await page.mouse.move(920, 420, { steps: 20 });
await page.mouse.up();
await page.waitForTimeout(1200);
await page.screenshot({ path: path.join(folder, "turn-right.png") });
const afterMove = JSON.parse(await page.locator("canvas").getAttribute("data-forest-metrics") || "{}");
const gpu = await page.evaluate(() => { const gl = document.querySelector("canvas")?.getContext("webgl2"); const ext = gl?.getExtension("WEBGL_debug_renderer_info"); return ext && gl?.getParameter(ext.UNMASKED_RENDERER_WEBGL); });
const canvasState = await page.evaluate(() => {
  const canvas = document.querySelector("canvas");
  const gl = canvas?.getContext("webgl2");
  if (!canvas || !gl) return { available: false };
  const pixel = new Uint8Array(4);
  gl.readPixels(Math.floor(canvas.width / 2), Math.floor(canvas.height / 2), 1, 1, gl.RGBA, gl.UNSIGNED_BYTE, pixel);
  return { available: true, contextLost: gl.isContextLost(), centerPixel: [...pixel], width: canvas.width, height: canvas.height };
});
await page.close();
const videoPath = await page.video()?.path();
await context.close();
await browser.close();
if (videoPath) await copyFile(videoPath, path.join(folder, "source-forest-free-walk.webm"));
const result = { loadedMs, initial, afterMove, gpu, canvasState, validRender: issues.length === 0 && !canvasState.contextLost, issues };
await writeFile(path.join(folder, "results.json"), JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
