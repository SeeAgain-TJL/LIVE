import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { chromium } from "playwright";

const folder = path.join(process.env.LOCALAPPDATA, "UNIVERSE-OF-ME", "asset-audit", "candidate-assets", "pine-evidence");
await mkdir(folder, { recursive: true });
const browser = await chromium.launch({ channel: "chrome", headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1, recordVideo: { dir: folder, size: { width: 1440, height: 900 } } });
const page = await context.newPage();
const issues = [];
page.on("console", message => { if (message.type() === "error") issues.push(`console: ${message.text()}`); });
page.on("pageerror", error => issues.push(`page: ${error.message}`));
page.on("requestfailed", request => issues.push(`request: ${request.url()} ${request.failure()?.errorText}`));
const started = Date.now();
await page.goto("http://127.0.0.1:3310/forest-lab", { waitUntil: "domcontentloaded" });
await page.locator("canvas[data-forest-ready='true']").waitFor({ timeout: 120000 });
const loadedMs = Date.now() - started;
await page.waitForTimeout(5000);
await page.locator(".forest-lab-bar").evaluate(element => { element.style.display = "none"; });
await page.screenshot({ path: path.join(folder, "webgl-source-camera-medium.png") });
const initial = await page.locator("canvas").getAttribute("data-forest-metrics");
await page.locator("canvas").click({ position: { x: 720, y: 450 } });
await page.keyboard.down("w");
await page.waitForTimeout(2100);
await page.keyboard.up("w");
await page.screenshot({ path: path.join(folder, "webgl-walk-near.png") });
await page.mouse.move(760, 450);
await page.mouse.down();
await page.mouse.move(1080, 390, { steps: 24 });
await page.mouse.up();
await page.waitForTimeout(1200);
await page.screenshot({ path: path.join(folder, "webgl-look-far.png") });
const afterWalk = await page.locator("canvas").getAttribute("data-forest-metrics");
const gpu = await page.evaluate(() => {
  const gl = document.querySelector("canvas")?.getContext("webgl2");
  const debug = gl?.getExtension("WEBGL_debug_renderer_info");
  return { vendor: debug && gl?.getParameter(debug.UNMASKED_VENDOR_WEBGL), renderer: debug && gl?.getParameter(debug.UNMASKED_RENDERER_WEBGL), userAgent: navigator.userAgent };
});
await page.close();
await context.close();
await browser.close();
const data = { loadedMs, initial: initial && JSON.parse(initial), afterWalk: afterWalk && JSON.parse(afterWalk), gpu, issues };
await writeFile(path.join(folder, "measurements.json"), JSON.stringify(data, null, 2));
console.log(JSON.stringify(data, null, 2));
